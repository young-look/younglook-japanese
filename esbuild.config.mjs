import { execSync } from "node:child_process";
import esbuild from "esbuild";
import process from "node:process";

const banner = `/*
THIS IS A GENERATED/BUNDLED FILE BY ESBUILD
if you want to view the source, please visit the github repository of this plugin
*/
`;

// 🔒 分支即环境：**dev 分支 = 连本机，master 分支 = 连线上**。
// 看一眼当前分支就知道构建出来的是什么，不靠记 npm 脚本语义。
// 显式参数可以覆盖分支默认（`build:prod` / `build:dev`，提前出线上包验证时用）；
// git 不可用或 detached HEAD 时按 dev 处理——宁可连本机，也不能连线上。
function gitBranch() {
    try {
        return execSync("git branch --show-current", { encoding: "utf8" }).trim();
    } catch {
        return "";
    }
}

const branch = gitBranch();
// `production` / `dev` = 显式指定环境（一次性构建）；`--watch` = 挂 watch；
// 什么都不传 = 一次性构建，环境跟分支走。
const args = process.argv.slice(2);
const forceProd = args.includes("production");
const forceDev = args.includes("dev");
const watchMode = args.includes("--watch");
const prod = forceProd ? true : forceDev ? false : branch === "master";
/** Obsidian 在运行时提供 `obsidian` / `electron` / 内置 CodeMirror 模块，不能打进产物。 */
const external = [
  "obsidian",
  "electron",
  "@codemirror/autocomplete",
  "@codemirror/collab",
  "@codemirror/commands",
  "@codemirror/language",
  "@codemirror/lint",
  "@codemirror/search",
  "@codemirror/state",
  "@codemirror/view",
  "@lezer/common",
  "@lezer/highlight",
  "@lezer/lr",
];

console.log(`[esbuild] 分支: ${branch || "未知"} → 构建: ${prod ? "prod（连线上）" : "dev（连本机）"}${forceProd || forceDev ? "（显式指定）" : ""}`);

const context = await esbuild.context({
  banner: { js: banner },
  entryPoints: ["src/main.ts"],
  bundle: true,
  // 图片资源以 dataurl 内联进 main.js（海獭 logo 等）：产物保持单文件，
  // 不引入「旁边散一个内容哈希 png、发布/安装要跟着拷」的问题。
  // .svg 走 text：存储页那三枚去向图标要拿源码现插进 DOM（让 fill="currentColor"
  // 跟着主题走），dataurl 进去就只剩 `<img>` 一条路、颜色就锁死了。
  // .mp4/.srt = 内置演示素材：dataurl/text 静态打进 main.js（见 services/demoAssets.ts）
  // —— 社区商店/BRAT 只装 Release 三件套，plugin/demo/ 目录不跟过去，不打包
  // 公开渠道用户就永远没有演示素材。词典 17MB 太大走按需下载，demo 1.1MB 值得进包。
  // ⚠️ 这一段与 scripts/release.mjs 必须逐项对齐 —— 发版脚本漏了哪个 loader，
  //    就会在 build 时才炸（2026-10-09 就是漏了 .png 静默停发）。
  loader: { ".png": "dataurl", ".svg": "text", ".mp4": "dataurl", ".srt": "text" },
  external,
  format: "cjs",
  target: "es2020",
  // 🔒 环境在构建时定死（dev 分支连本机，master 分支连线上，见文件头）。
  // 只留这一个注入点，src/config/env.ts 是它们唯一的读取处。
  define: {
    __YL_ENV__: JSON.stringify(prod ? "prod" : "dev"),
    __YL_BRANCH__: JSON.stringify(branch),
  },
  // 默认 charset 是 ascii，中文会被转义成 \uXXXX —— 用户可见文案在产物里没法直接看，
  // 排查问题时要反过来查码点。留成 utf8，产物仍然正确，只是好读得多。
  charset: "utf8",
  logLevel: "info",
  sourcemap: prod ? false : "inline",
  treeShaking: true,
  outfile: "main.js",
  minify: prod,
  platform: "node",
});

if (watchMode) {
  await context.watch();
} else {
  await context.rebuild();
  await context.dispose();
  process.exit(0);
}

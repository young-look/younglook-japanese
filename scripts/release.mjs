#!/usr/bin/env node
/**
 * 出一份线上更新包：构建 prod 三件套到 release/<version>/，生成 latest.json。
 *
 * ⚠️ 刻意**不经过 plugin/main.js**：开发 vault 软链的那份永远是 dev 构建，
 * 发版不能把它顶掉（这是"分支即环境"的边界）。这里用 esbuild API 直接
 * 把 prod 产物落到 release/<version>/main.js。
 *
 * 用法:
 *   npm_package_version 已由 package.json 决定（node versions.mjs 同步进 manifest）
 *   node scripts/release.mjs ["本次更新的说明文字"]
 *
 * 推送到服务端: ./yolo plugin-release（rsync 到 storage/assets/packages/）
 */
import { createHash } from "node:crypto";
import fs from "node:fs";
import path from "node:path";
import { execSync } from "node:child_process";
import { fileURLToPath } from "node:url";
import esbuild from "esbuild";

const pluginDir = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const pkg = JSON.parse(fs.readFileSync(path.join(pluginDir, "package.json"), "utf8"));
const manifest = JSON.parse(fs.readFileSync(path.join(pluginDir, "manifest.json"), "utf8"));

if (manifest.version !== pkg.version) {
  console.error(`✗ 版本不同步：package.json=${pkg.version}，manifest.json=${manifest.version}`);
  console.error("  先在 plugin/ 目录跑: npm_package_version=<版本> node versions.mjs");
  process.exit(1);
}

fs.rmSync(path.join(pluginDir, "release"), { recursive: true, force: true });
const outDir = path.join(pluginDir, "release", pkg.version);
fs.mkdirSync(outDir, { recursive: true });

let branch = "";
try {
  branch = execSync("git branch --show-current", { encoding: "utf8" }).trim();
} catch {
  branch = "";
}
if (branch !== "master") {
  console.error(`✗ 发版只允许在 master 分支（当前：${branch || "未知"}）。`);
  process.exit(1);
}

// ── 与 esbuild.config.mjs 的 prod 构建保持一致（external 清单与 loader 两边同步维护）──
const external = [
  "obsidian",
  "electron",
  "@codemirror/autocomplete",
  "@codemirror/collab",
  "@codemirror/commands",
  "@codemirror/language",
  "@codemirror/lint",
  "@codemirror/search",
  "@codemirror/state",
  "@codemirror/view",
  "@lezer/common",
  "@lezer/highlight",
  "@lezer/lr",
];

await esbuild.build({
  banner: { js: "/*\nTHIS IS A GENERATED/BUNDLED FILE BY ESBUILD\n*/\n" },
  entryPoints: [path.join(pluginDir, "src/main.ts")],
  bundle: true,
  // 图片资源以 dataurl 内联进 main.js（海獭 logo 等）：产物保持单文件。
  // .svg 走 text（存储页那三枚去向图标要拿源码现插进 DOM）。
  // 演示素材（demo.mp4 / demo.srt）**不再内联**（曾把 main.js 撑到近 6MB），
  // 改走服务端按需下载：scripts/demo-manifest.mjs + services/demoPack.ts。
  // ⚠️ 与 esbuild.config.mjs 必须一致 —— 少了哪一项，凡是 import 了对应资源的
  //    产物都会构建失败（发版路径曾因漏 .png 断掉，线上停在旧版本没人察觉）。
  loader: { ".png": "dataurl", ".svg": "text" },
  external,
  format: "cjs",
  target: "es2020",
  define: {
    __YL_ENV__: JSON.stringify("prod"),
    __YL_BRANCH__: JSON.stringify(branch),
  },
  charset: "utf8",
  logLevel: "info",
  sourcemap: false,
  treeShaking: true,
  outfile: path.join(outDir, "main.js"),
  minify: true,
  platform: "node",
});

fs.copyFileSync(path.join(pluginDir, "manifest.json"), path.join(outDir, "manifest.json"));
fs.copyFileSync(path.join(pluginDir, "styles.css"), path.join(outDir, "styles.css"));

// 演示素材走**独立的按需下载通道**（服务端 /storage/media/videos/，见 scripts/demo-manifest.mjs
// 与 ./yolo demo-release），不随发布三件套走。发版前若换过演示素材，先跑
// `npm run demo-manifest` + `./yolo demo-release`，再发插件。

const files = {};
for (const name of ["main.js", "manifest.json", "styles.css"]) {
  const buffer = fs.readFileSync(path.join(outDir, name));
  files[name] = {
    // 相对路径：插件拼在 serverUrl 后面，换域名也不用重发 latest.json
    url: `/storage/assets/packages/${pkg.version}/${name}`,
    sha256: createHash("sha256").update(buffer).digest("hex"),
  };
}

const latest = {
  version: pkg.version,
  notes: process.argv[2] ?? "",
  files,
};
fs.writeFileSync(
  path.join(pluginDir, "release", "latest.json"),
  `${JSON.stringify(latest, null, 2)}\n`,
);

console.log(`\n✓ 发版包就绪: plugin/release/ (${pkg.version})`);
console.log("  校验产物后推送到服务端: ./yolo plugin-release");
